const PRE = /*__PRE__*/{}
/*__CONSTANTS__*/
/*__SCHEMAS__*/
const LEDGER2 = { ...LEDGER, required: [...LEDGER.required, 'blocked_searches'], properties: { ...LEDGER.properties, blocked_searches: num } }
const VERDICT2 = { ...VERDICT, required: [...VERDICT.required, 'searches', 'blocked_searches'], properties: { ...VERDICT.properties, searches: num, blocked_searches: num } }
const CHALLENGE2 = { ...CHALLENGE, required: [...CHALLENGE.required, 'searches', 'blocked_searches'], properties: { ...CHALLENGE.properties, searches: num, blocked_searches: num } }
const BLOCKED_NOTE = `\nIf a WebSearch call returns "Web search was not performed", stop searching, count those calls in blocked_searches, and return what you have, with anything you couldn't check marked not_reached or unverifiable.`
// Expected searches per agent, used to keep each batch under the per-turn cap.
const EST = { large: { A: 26, B: 22 }, medium: { A: 18, B: 16 }, small: { ALL: 20 }, GAPS: 16, verify: 6, challenge: 8 }
const { batch, cap: CAP, items } = args
